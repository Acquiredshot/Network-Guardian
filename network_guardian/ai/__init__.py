# ---------------------------------------------------------------------------
# Data types
# ---------------------------------------------------------------------------


class PredictionType(Enum):
    ANOMALY = "anomaly"
    CLASSIFICATION = "classification"
    RECOMMENDATION = "recommendation"
    FORECAST = "forecast"


@dataclass
class Prediction:
    """Output of an ML model."""

    prediction_type: PredictionType
    label: str
    confidence: float
    details: dict[str, Any] = field(default_factory=dict)
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))


@dataclass
class Recommendation:
    """A recommended action generated by the AI component."""

    title: str
    description: str
    priority: Severity = Severity.INFO
    category: str = "general"
    actions: list[str] = field(default_factory=list)


# ---------------------------------------------------------------------------
# Model interface
# ---------------------------------------------------------------------------


class MLModel(ABC):
    """Abstract base class for ML models used by the AI engine."""

    name: str = "base_model"

    @abstractmethod
    async def predict(self, features: dict[str, Any]) -> Prediction:
        """Run inference on a feature set."""

    @abstractmethod
    async def train(self, data: list[dict[str, Any]]) -> dict[str, Any]:
        """Train or fine-tune the model. Returns training metrics."""

    def health_check(self) -> dict[str, Any]:
        return {"model": self.name, "status": "ok"}


