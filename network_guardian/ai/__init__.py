class AIEngine:
    """Coordinates ML models and generates recommendations."""

    def __init__(self, config: Config, event_bus: EventBus) -> None:
        self.config = config
        self.event_bus = event_bus
        self._models: dict[str, MLModel] = {}

        # Lazy-initialised advanced subsystems
        self._audit_analyzer: NetworkAuditAnalyzer | None = None
        self._smart_automation: SmartAutomation | None = None
        self._forecasters: dict[str, Forecaster] = {}

        # Register built-in models
        self.register_model(AnomalyClassifier())
        self.register_model(PatternRecogniser())

    def register_model(self, model: MLModel) -> None:
        self._models[model.name] = model
        logger.info("AI model registered: %s", model.name)

    def get_model(self, name: str) -> MLModel:
        return self._models[name]

    async def classify_anomaly(self, features: dict[str, Any]) -> Prediction:
        """Classify whether a metric reading is anomalous."""
        model = self._models["anomaly_classifier"]
        prediction = await model.predict(features)
        if prediction.label == "anomaly":
            await self.event_bus.publish(Event(
                topic="ai.anomaly_detected",
                data={"prediction": prediction},
            ))
        return prediction

    async def recognise_pattern(self, features: dict[str, Any]) -> Prediction:
        """Attempt to classify a network traffic pattern."""
        model = self._models["pattern_recogniser"]
        return await model.predict(features)

    async def generate_recommendations(
        self, findings: list[Finding], metrics: list[Metric]
    ) -> list[Recommendation]:
        """Analyse findings and metrics to produce actionable recommendations."""
        recommendations: list[Recommendation] = []

        # Group findings by severity
        critical = [f for f in findings if f.severity in (Severity.HIGH, Severity.CRITICAL)]
        if critical:
            recommendations.append(Recommendation(
                title="Address critical findings immediately",
                description=f"{len(critical)} high/critical finding(s) detected.",
                priority=Severity.CRITICAL,
                category="security",
                actions=[f"Fix: {f.title} on {f.host}" for f in critical],
            ))

        medium = [f for f in findings if f.severity == Severity.MEDIUM]
        if medium:
            recommendations.append(Recommendation(
                title="Review medium-severity findings",
                description=f"{len(medium)} medium finding(s) should be reviewed.",
                priority=Severity.MEDIUM,
                category="security",
                actions=[f"Review: {f.title}" for f in medium],
            ))

        await self.event_bus.publish(Event(
            topic="ai.recommendations_generated",
            data={"count": len(recommendations)},
        ))
        return recommendations

    @property
    def model_names(self) -> list[str]:
        return list(self._models.keys())

    # -- Advanced subsystems (lazy) -------------------------------------

    @property
    def audit_analyzer(self) -> NetworkAuditAnalyzer:
        """Lazy-initialised network audit analyzer with ensemble detector."""
        if self._audit_analyzer is None:
            from network_guardian.ai.audit_analyzer import NetworkAuditAnalyzer
            self._audit_analyzer = NetworkAuditAnalyzer()
        return self._audit_analyzer

    @property
    def smart_automation(self) -> SmartAutomation:
        """Lazy-initialised smart task automation engine."""
        if self._smart_automation is None:
            from network_guardian.ai.smart_automation import SmartAutomation
            self._smart_automation = SmartAutomation()
        return self._smart_automation

    def get_forecaster(self, method: str = "arima", **kwargs: Any) -> Forecaster:
        """Get or create a forecaster by method name."""
        if method not in self._forecasters:
            if method == "arima":
                from network_guardian.ai.forecasting import ARIMAForecaster
                self._forecasters[method] = ARIMAForecaster(**kwargs)
            elif method == "seasonal":
                from network_guardian.ai.forecasting import SeasonalDecomposer
                self._forecasters[method] = SeasonalDecomposer(**kwargs)
            elif method == "holt_winters":
                from network_guardian.ai.forecasting import HoltWintersForecaster
                self._forecasters[method] = HoltWintersForecaster(**kwargs)
            else:
                raise ValueError(f"Unknown forecaster method: {method}")
        return self._forecasters[method]

    # -- High-level API bridging new modules ----------------------------

    async def forecast(
        self, series: list[float], steps: int = 10, method: str = "arima", **kwargs: Any,
    ) -> ForecastResult:
        """Fit a forecaster on *series* and predict *steps* ahead."""
        forecaster = self.get_forecaster(method, **kwargs)
        forecaster.fit(series)
        result = forecaster.predict(steps)
        await self.event_bus.publish(Event(
            topic="ai.forecast_generated",
            data={"method": method, "steps": steps},
        ))
        return result

    async def analyse_fleet(self, hosts: list[Host]) -> list[HostRiskProfile]:
        """Run audit analysis across a fleet of hosts."""
        profiles = self.audit_analyzer.analyse(hosts)
        await self.event_bus.publish(Event(
            topic="ai.fleet_analysed",
            data={"host_count": len(hosts), "profiles": len(profiles)},
        ))
        return profiles

    async def recommend_tasks(
        self,
        findings: list[Finding],
        available_tasks: list[str],
        history: list[TaskResult] | None = None,
    ) -> list[TaskRecommendation]:
        """Generate prioritised task recommendations from findings."""
        if history:
            self.smart_automation.learn_from_history(history)
        recommendations = self.smart_automation.recommend_tasks(findings, available_tasks)
        await self.event_bus.publish(Event(
            topic="ai.tasks_recommended",
            data={"count": len(recommendations)},
        ))
        return recommendations
