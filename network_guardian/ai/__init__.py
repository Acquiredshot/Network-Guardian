# Built-in models
# ---------------------------------------------------------------------------


class AnomalyClassifier(MLModel):
    """Statistical anomaly classifier (decision-tree-style rules).

    This is a lightweight built-in classifier. For heavy ML workloads,
    register a TensorFlow/PyTorch-backed model via the plugin system.
    """

    name = "anomaly_classifier"

    def __init__(self) -> None:
        self._thresholds: dict[str, float] = {}
        self._trained = False

    async def predict(self, features: dict[str, Any]) -> Prediction:
        value = features.get("value", 0.0)
        metric_name = features.get("metric_name", "unknown")
        threshold = self._thresholds.get(metric_name, 2.0)

        z_score = abs(features.get("z_score", 0.0))
        is_anomaly = z_score > threshold

        confidence = self._compute_confidence(is_anomaly, z_score, threshold)

        return Prediction(
            prediction_type=PredictionType.ANOMALY,
            label="anomaly" if is_anomaly else "normal",
            confidence=confidence,
            details={"metric": metric_name, "value": value, "z_score": z_score},
        )

    @staticmethod
    def _compute_confidence(is_anomaly: bool, z_score: float, threshold: float) -> float:
        if is_anomaly:
            return min(z_score / (threshold * 2), 1.0)
        if threshold:
            return 1.0 - (z_score / threshold)
        return 1.0

    async def train(self, data: list[dict[str, Any]]) -> dict[str, Any]:
        """Learn per-metric thresholds from labelled data."""
        for record in data:
            name = record.get("metric_name", "unknown")
            threshold = record.get("threshold")
            if threshold is not None:
                self._thresholds[name] = float(threshold)
        self._trained = True
        return {"status": "trained", "metrics_configured": len(self._thresholds)}


class PatternRecogniser(MLModel):
    """Rule-based pattern recogniser for network traffic patterns.

    Placeholder for a random-forest / decision-tree model.
    """

    name = "pattern_recogniser"

    def __init__(self) -> None:
        self._patterns: list[dict[str, Any]] = []

    async def predict(self, features: dict[str, Any]) -> Prediction:
        # Placeholder — match against known patterns
        return Prediction(
            prediction_type=PredictionType.CLASSIFICATION,
            label="unknown",
            confidence=0.0,
            details=features,
        )

    async def train(self, data: list[dict[str, Any]]) -> dict[str, Any]:
        self._patterns = data
        return {"status": "trained", "patterns_loaded": len(data)}


